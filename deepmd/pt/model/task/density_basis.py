@Fitting.register("density_basis")
class DensityBasisHead(Fitting):
    """Expand atomic density coefficients on a radial basis around each atom.

    Unlike the standard fittings, this head is not called with only the
    descriptor and the atom types: the owning atomic model additionally
    provides the grid-atom pairs (distances, neighbor types, padding mask and
    the local-row index that shares coefficients with periodic images). The
    pair layout follows the directional grid neighbor list, so scattering the
    pair contributions onto the grid points reduces to a sum over the
    neighbor axis.

    Parameters
    ----------
    ntypes : int
        Element count, including the reserved grid type (its embedding row is
        never used: grid points are expansion centers, never neighbors).
    dim_descrpt : int
        Dimension of the scalar descriptor of every local atom.
    rcut : float
        Cutoff radius of the radial expansion. Must match the descriptor
        cutoff, which also builds the grid neighbor list.
    channels : int
        Number of density coefficient channels per atom.
    n_radial : int
        Number of radial basis functions; also the type-embedding width.
    basis_type : str
        Radial basis type, see :class:`RadialBasis` ("bessel" by default).
    radial_neurons : list[int]
        Hidden layer sizes of the radial MLP.
    use_equivariant : bool
        Whether to also expand the equivariant (l >= 1) density coefficients
        taken from the descriptor's SO(3) latent with real spherical
        harmonics of the grid-atom direction. When False (default) the head
        is exactly the scalar l = 0 expansion and the module tree (and hence
        old checkpoints) is unchanged.
    coef_lmax : int
        Maximum angular degree of the equivariant expansion, at most 6.
        Degrees up to ``latent_lmax`` are projected from the descriptor
        latent directly; higher degrees (l = 3..6, requiring a latent with
        ``latent_lmax >= 2``) are generated by Clebsch-Gordan coupling of
        the latent l = 1 and l = 2 blocks (1 x 2 -> 3, 2 x 2 -> 4,
        3 x 2 -> 5, 4 x 2 -> 6) inside the head. Only used when
        ``use_equivariant`` is True.
    cg_width : int
        Channel width of the Clebsch-Gordan source projection, only used
        when ``coef_lmax > 2``.
    latent_lmax : int
        Maximum angular degree of the descriptor's SO(3) latent. Injected
        by the model builder; 0 when ``use_equivariant`` is False.
    latent_channels : int
        Channel count of the descriptor's SO(3) latent. Injected by the
        model builder; 0 when ``use_equivariant`` is False.
    precision : str
        Numerical precision of the head parameters.
    seed : int, optional
        Random seed for parameter initialization.
    trainable : bool
        Whether the parameters of the head are trainable.
    exclude_types : list[int]
        Atom types whose density contribution is excluded.
    type_map : list[str], optional
        A list of strings giving the name of each type of atoms.
    """

    # exponent of the C^3 cutoff envelope, shared by the radial basis and the
    # final response gate
    CUTOFF_EXPONENT = 7

    # make jit happy with torch 2.0.0
    exclude_types: list[int]

    def __init__(
        self,
        ntypes: int,
        dim_descrpt: int,
        rcut: float,
        channels: int = 4,
        n_radial: int = 16,
        basis_type: str = "bessel",
        radial_neurons: list[int] = [32, 32],
        use_equivariant: bool = False,
        coef_lmax: int = 2,
        cg_width: int = 8,
        latent_lmax: int = 0,
        latent_channels: int = 0,
        numb_fparam: int = 0,
        numb_aparam: int = 0,
        dim_case_embd: int = 0,
        precision: str = DEFAULT_PRECISION,
        seed: int | list[int] | None = None,
        trainable: bool = True,
        exclude_types: list[int] = [],
        type_map: list[str] | None = None,
        mixed_types: bool = True,
        **kwargs: Any,
    ) -> None:
        super().__init__()
        del kwargs
        if numb_fparam > 0:
            raise ValueError(
                "density_basis fitting does not support frame parameters (fparam) yet"
            )
        if numb_aparam > 0:
            raise ValueError(
                "density_basis fitting does not support atomic parameters "
                "(aparam): the coefficients are predicted from the descriptor "
                "alone"
            )
        if dim_case_embd > 0:
            raise ValueError(
                "density_basis fitting does not support case embeddings yet"
            )
        self.ntypes = ntypes
        self.dim_descrpt = dim_descrpt
        self.rcut = float(rcut)
        if self.rcut <= 0.0:
            raise ValueError("`rcut` must be positive")
        self.channels = int(channels)
        self.n_radial = int(n_radial)
        self.basis_type = str(basis_type)
        self.radial_neurons = list(radial_neurons)
        self.precision = precision
        self.prec = PRECISION_DICT[precision]
        self.seed = seed
        self.type_map = type_map
        self.mixed_types = mixed_types
        self.trainable = bool(trainable)
        self.numb_fparam = 0
        self.numb_aparam = 0
        # order matters, should be placed after the assignment of ntypes
        self.reinit_exclude(exclude_types)

        # equivariant (l >= 1) expansion, off by default; when off the module
        # tree is byte-identical to the scalar-only head so that old
        # checkpoints load with strict=True
        self.use_equivariant = bool(use_equivariant)
        self.latent_lmax = int(latent_lmax)
        self.latent_channels = int(latent_channels)
        if self.use_equivariant:
            if self.latent_lmax < 1:
                raise ValueError(
                    "use_equivariant requires a descriptor SO(3) latent with "
                    f"lmax >= 1, got latent_lmax={self.latent_lmax}"
                )
            if self.latent_channels <= 0:
                raise ValueError(
                    "use_equivariant requires a positive latent_channels, "
                    f"got {self.latent_channels}"
                )
            self.coef_lmax = int(coef_lmax)
            if not 1 <= self.coef_lmax <= 6:
                raise ValueError(
                    f"coef_lmax must be in 1..6 when use_equivariant is True, "
                    f"got {coef_lmax}"
                )
            if self.coef_lmax > self.latent_lmax and self.latent_lmax < 2:
                raise ValueError(
                    f"coef_lmax={self.coef_lmax} exceeds the descriptor latent "
                    f"lmax={self.latent_lmax}: degrees l >= 3 are generated by "
                    "Clebsch-Gordan coupling of the latent l = 1 and l = 2 "
                    "blocks, which requires latent_lmax >= 2"
                )
            self.so3_lmax = min(self.coef_lmax, self.latent_lmax)
            self.cg_width = int(cg_width)
        else:
            self.coef_lmax = 0
            self.cg_width = 0
        # the radial MLP emits one response block per angular degree
        self.radial_out_dim = self.channels * (1 + self.coef_lmax)

        # per-atom density coefficients from the scalar descriptor
        self.coef_proj = MLPLayer(
            self.dim_descrpt,
            self.channels,
            bias=True,
            activation_function=None,
            precision=self.precision,
            seed=child_seed(self.seed, 0),
            trainable=self.trainable,
        )
        # element-dependent radial response of the grid-atom distance
        self.radial_basis = RadialBasis(
            self.rcut,
            basis_type=self.basis_type,
            n_radial=self.n_radial,
            dtype=self.prec,
            exponent=self.CUTOFF_EXPONENT,
            trainable=self.trainable,
        )
        self.type_embedding = TypeEmbedNet(
            self.ntypes,
            self.n_radial,
            precision=self.precision,
            seed=child_seed(self.seed, 1),
            type_map=type_map,
            trainable=self.trainable,
        )
        self.radial_mlp = RadialMLP(
            [2 * self.n_radial, *self.radial_neurons, self.radial_out_dim],
            activation_function="silu",
            dtype=self.prec,
            trainable=self.trainable,
            # no RMSNorm: the radial features must vanish smoothly with the
            # cutoff envelope instead of being renormalized away from zero
            radial_norm=False,
            seed=child_seed(self.seed, 2),
        )
        if self.use_equivariant:
            # per-l equivariant projection of the descriptor latent to the
            # density coefficient channels; the l = 0 block is unused (the
            # scalar coefficients come from coef_proj)
            self.coef_proj_so3 = SO3Linear(
                lmax=self.so3_lmax,
                in_channels=self.latent_channels,
                out_channels=self.channels,
                n_focus=1,
                dtype=self.prec,
                mlp_bias=False,
                trainable=self.trainable,
                seed=child_seed(self.seed, 3),
            )
            # orthonormal 3x3 basis aligned with the SeZM packed (l, m)
            # layout; it intertwines the packed Wigner-D rotation with the
            # Cartesian rotation X -> R X R^T, so the contraction of the
            # equivariant coefficients with the direction tensor built in
            # this basis is exactly rotation invariant. Only used for the
            # l <= 2 path; coef_lmax > 2 goes through the higher-l
            # spherical-harmonics path instead.
            if self.coef_lmax <= 2:
                self.register_buffer(
                    "cart_basis",
                    build_cartesian_basis(
                        self.coef_lmax, dtype=self.prec, device=env.DEVICE
                    ),
                    persistent=True,
                )
            else:
                # higher-degree (l >= 3) coefficients generated by
                # Clebsch-Gordan coupling of the latent l = 1 and l = 2
                # blocks; the coupling tensors and the spherical-harmonics
                # transforms are deterministic constants solved against the
                # Wigner-D convention (see sezm_nn.higher_l), registered as
                # non-persistent buffers so they rebuild on construction
                # without entering the serialized state
                self.cg_proj = SO3Linear(
                    lmax=self.latent_lmax,
                    in_channels=self.latent_channels,
                    out_channels=self.cg_width,
                    n_focus=1,
                    dtype=self.prec,
                    mlp_bias=False,
                    trainable=self.trainable,
                    seed=child_seed(self.seed, 4),
                )
                mixes: dict[str, torch.nn.Module] = {}
                if self.coef_lmax >= 3:
                    mixes["l3"] = MLPLayer(
                        self.cg_width * self.cg_width,
                        self.channels,
                        bias=False,
                        activation_function=None,
                        precision=self.precision,
                        seed=child_seed(self.seed, 5),
                        trainable=self.trainable,
                    )
                if self.coef_lmax >= 4:
                    mixes["l4"] = MLPLayer(
                        self.cg_width * self.cg_width,
                        self.channels,
                        bias=False,
                        activation_function=None,
                        precision=self.precision,
                        seed=child_seed(self.seed, 6),
                        trainable=self.trainable,
                    )
                if self.coef_lmax >= 5:
                    mixes["l5"] = MLPLayer(
                        self.channels * self.cg_width,
                        self.channels,
                        bias=False,
                        activation_function=None,
                        precision=self.precision,
                        seed=child_seed(self.seed, 7),
                        trainable=self.trainable,
                    )
                if self.coef_lmax >= 6:
                    mixes["l6"] = MLPLayer(
                        self.channels * self.cg_width,
                        self.channels,
                        bias=False,
                        activation_function=None,
                        precision=self.precision,
                        seed=child_seed(self.seed, 8),
                        trainable=self.trainable,
                    )
                self.cg_mix = torch.nn.ModuleDict(mixes)
                transforms, couplings = build_higher_l_constants(self.coef_lmax)
                for ll, t in transforms.items():
                    self.register_buffer(
                        f"sh_transform_l{ll}",
                        t.to(dtype=self.prec, device=env.DEVICE),
                        persistent=False,
                    )
                for (l1, l2, l3), t in couplings.items():
                    self.register_buffer(
                        f"cg_{l1}{l2}{l3}",
                        t.to(dtype=self.prec, device=env.DEVICE),
                        persistent=False,
                    )
                self.register_buffer(
                    "sh_norm",
                    build_real_sh_norm(self.coef_lmax, device=torch.device("cpu")).to(
                        dtype=self.prec, device=env.DEVICE
                    ),
                    persistent=False,
                )
        # the type-embedding branch of the radial MLP does not vanish at the
        # cutoff on its own; the explicit envelope gate keeps the response
        # strictly zero for r >= rcut
        self.envelope = C3CutoffEnvelope(
            self.rcut,
            exponent=self.CUTOFF_EXPONENT,
            dtype=self.prec,
        )
        for param in self.parameters():
            param.requires_grad = self.trainable

    def reinit_exclude(
        self,
        exclude_types: list[int] = [],
    ) -> None:
        self.exclude_types = exclude_types
        self.emask = AtomExcludeMask(self.ntypes, self.exclude_types)

    def output_def(self) -> FittingOutputDef:
        return FittingOutputDef(
            [
                OutputVariableDef(
                    "density",
                    [1],
                    reducible=False,
                    r_differentiable=False,
                    c_differentiable=False,
                ),
            ]
        )

    def forward(
        self,
        descriptor: torch.Tensor,
        pair_atype: torch.Tensor,
        pair_dist: torch.Tensor,
        pair_mask: torch.Tensor,
        coef_gather_index: torch.Tensor,
        latent: torch.Tensor | None = None,
        pair_vec: torch.Tensor | None = None,
    ) -> torch.Tensor:
        """Evaluate the density on the grid points.

        Parameters
        ----------
        descriptor
            Scalar descriptor of the local atoms. nf x nloc x dim_descrpt.
        pair_atype
            Type of the neighbor atom of every grid-atom pair.
            nf x ngrid x nsel. Padding positions carry ``ntypes``, the zero
            padding row of the type embedding.
        pair_dist
            Grid-atom distance of every pair. nf x ngrid x nsel.
        pair_mask
            True for valid pairs; padding pairs contribute nothing.
            nf x ngrid x nsel.
        coef_gather_index
            Local-row index of the neighbor atom of every pair, i.e.
            ``mapping[grid_nlist]``, so periodic images share the
            coefficients of their local row. nf x ngrid x nsel.
        latent
            SO(3) equivariant latent of the local atoms with shape
            (nf * nloc, D, 1, latent_channels), packed (l, m) degree-major
            in the SeZM Wigner-D convention. Required when
            ``use_equivariant`` is True.
        pair_vec
            Grid-to-atom vector of every pair. nf x ngrid x nsel x 3.
            Required when ``use_equivariant`` is True.

        Returns
        -------
        torch.Tensor
            The density on the grid points. nf x ngrid x 1.
        """
        nf, ngrid, nsel = pair_dist.shape
        # nf x nloc x channels
        coef = self.coef_proj(descriptor.to(self.prec))
        # nf x ngrid x nsel x channels
        coef_pair = torch.gather(
            coef,
            1,
            coef_gather_index.reshape(nf, ngrid * nsel, 1).expand(
                -1, -1, self.channels
            ),
        ).view(nf, ngrid, nsel, self.channels)
        rr = pair_dist.reshape(nf * ngrid * nsel, 1).to(self.prec)
        # npair x n_radial
        rbf = self.radial_basis(rr)
        # nf x ngrid x nsel x n_radial
        tebd = self.type_embedding(pair_atype).to(self.prec)
        # npair x channels * (1 + coef_lmax)
        radial = self.radial_mlp(
            torch.cat([rbf, tebd.reshape(nf * ngrid * nsel, self.n_radial)], dim=-1)
        )
        radial = radial * self.envelope(rr)
        # atoms of the excluded types carry no density; padding rows of the
        # type index (ntypes) are clamped away, they are masked anyway
        keep = self.emask(
            pair_atype.clamp(max=self.ntypes - 1).reshape(nf, ngrid * nsel)
        ).view(nf, ngrid, nsel)
        pair_keep = pair_mask & (keep > 0)
        if not self.use_equivariant:
            radial = radial.view(nf, ngrid, nsel, self.channels)
            # nf x ngrid x nsel
            contrib = (coef_pair * radial).sum(dim=-1) * pair_keep.to(self.prec)
            # the pairs are grouped by grid point, so the scatter onto the
            # grid is a sum over the neighbor axis
            return contrib.sum(dim=-1).unsqueeze(-1)
        # the equivariant branch references modules that only exist when
        # use_equivariant is True; nesting it under is_scripting prunes the
        # whole branch under torch.jit.script (the scalar branch and the
        # error below stay scriptable)
        if not torch.jit.is_scripting():
            return self._forward_equivariant(
                descriptor,
                radial,
                coef_pair,
                pair_keep,
                coef_gather_index,
                latent,
                pair_vec,
            )
        raise RuntimeError(
            "density_basis with use_equivariant=True does not support "
            "torch.jit.script; evaluate the model eagerly"
        )

    def _forward_equivariant(
        self,
        descriptor: torch.Tensor,
        radial: torch.Tensor,
        coef_pair: torch.Tensor,
        pair_keep: torch.Tensor,
        coef_gather_index: torch.Tensor,
        latent: torch.Tensor | None,
        pair_vec: torch.Tensor | None,
    ) -> torch.Tensor:
        """Equivariant (l >= 1) part of the density expansion; eager-only."""
        if self.coef_lmax > 2:
            return self._forward_equivariant_higher(
                descriptor,
                radial,
                coef_pair,
                pair_keep,
                coef_gather_index,
                latent,
                pair_vec,
            )
        assert latent is not None, "latent is required when use_equivariant is True"
        assert pair_vec is not None, "pair_vec is required when use_equivariant is True"
        nf, ngrid, nsel = pair_keep.shape
        llmax = self.coef_lmax
        channels = self.channels
        nloc = descriptor.shape[1]
        dim_lm = (llmax + 1) * (llmax + 1)
        # nf x ngrid x nsel x (1 + llmax) x channels
        radial = radial.view(nf, ngrid, nsel, 1 + llmax, channels)
        # l = 0: scalar coefficients dotted with the l = 0 radial block
        contrib = (coef_pair * radial[..., 0, :]).sum(dim=-1)
        # l >= 1: equivariant coefficients contracted with the direction
        # tensor of the grid-atom direction, both expressed in the SeZM
        # packed (l, m) basis, so the contraction is exactly invariant
        # nf x nloc x D x channels
        coef_lm = self.coef_proj_so3(latent[:, :dim_lm].to(self.prec)).view(
            nf, nloc, dim_lm, channels
        )
        # nf x ngrid x nsel x D x channels
        coef_lm_pair = torch.gather(
            coef_lm,
            1,
            coef_gather_index.reshape(nf, ngrid * nsel, 1, 1).expand(
                -1, -1, dim_lm, channels
            ),
        ).view(nf, ngrid, nsel, dim_lm, channels)
        # Cartesian direction tensor, normalized to unit Frobenius norm per
        # irreducible block; the l = 0 (trace) row vanishes and is unused.
        # Zero-length vectors only occur on masked padding pairs.
        vec = pair_vec.reshape(nf * ngrid * nsel, 3).to(self.prec)
        r_hat = vec / vec.norm(dim=-1, keepdim=True).clamp_min(1e-12)
        a0, s0 = build_edge_cartesian_tensors(r_hat)
        direction = a0 / math.sqrt(2.0)
        if llmax >= 2:
            direction = direction + s0 / math.sqrt(2.0 / 3.0)
        # npair x D: packed direction coefficients in the SeZM basis
        udir = torch.einsum("dij,eij->ed", self.cart_basis, direction).view(
            nf, ngrid, nsel, dim_lm, 1
        )
        for ll in range(1, llmax + 1):
            ss = ll * ll
            ee = (ll + 1) * (ll + 1)
            # sum_m c_lm * u_lm -> nf x ngrid x nsel x channels
            angular = (coef_lm_pair[..., ss:ee, :] * udir[..., ss:ee, :]).sum(dim=-2)
            contrib = contrib + (radial[..., ll, :] * angular).sum(dim=-1)
        contrib = contrib * pair_keep.to(self.prec)
        return contrib.sum(dim=-1).unsqueeze(-1)

    def _cg_couple(
        self,
        coupling: torch.Tensor,
        feat_a: torch.Tensor,
        feat_b: torch.Tensor,
        mix: torch.nn.Module,
    ) -> torch.Tensor:
        """Couple packed coefficient blocks of degrees ``l1``, ``l2`` onto ``l3``.

        ``feat_a`` has shape ``(N, 2*l1 + 1, C1)`` and ``feat_b``
        ``(N, 2*l2 + 1, C2)``, both in the SeZM packed convention; the
        output is ``(N, 2*l3 + 1, channels)``. The channel mixing is
        m-independent and bias-free, so the coupling is equivariant.
        """
        prod = torch.einsum("mno,xmk,xnl->xokl", coupling, feat_a, feat_b)
        prod = prod.reshape(prod.shape[0], prod.shape[1], -1)
        return mix(prod)

    def _forward_equivariant_higher(
        self,
        descriptor: torch.Tensor,
        radial: torch.Tensor,
        coef_pair: torch.Tensor,
        pair_keep: torch.Tensor,
        coef_gather_index: torch.Tensor,
        latent: torch.Tensor | None,
        pair_vec: torch.Tensor | None,
    ) -> torch.Tensor:
        """Equivariant expansion for ``coef_lmax > 2``; eager-only.

        Coefficients of degrees up to ``so3_lmax`` come from the SO(3)
        projection of the latent directly; higher degrees are generated by
        Clebsch-Gordan coupling of the latent l = 1 and l = 2 blocks
        (``1 x 2 -> 3``, ``2 x 2 -> 4``, ``3 x 2 -> 5``, ``4 x 2 -> 6``).
        The direction spherical harmonics are evaluated per pair chunk and
        contracted per degree, so memory stays bounded regardless of the
        pair count.
        """
        assert latent is not None, "latent is required when use_equivariant is True"
        assert pair_vec is not None, "pair_vec is required when use_equivariant is True"
        nf, ngrid, nsel = pair_keep.shape
        llmax = self.coef_lmax
        channels = self.channels
        nloc = descriptor.shape[1]
        so3_dim = (self.so3_lmax + 1) * (self.so3_lmax + 1)
        n_at = nf * nloc
        # per-atom coefficient blocks in the packed convention
        coef_lm = self.coef_proj_so3(latent[:, :so3_dim].to(self.prec)).reshape(
            n_at, so3_dim, channels
        )
        blocks: dict[int, torch.Tensor] = {}
        for ll in range(1, min(self.so3_lmax, llmax) + 1):
            blocks[ll] = coef_lm[:, ll * ll : (ll + 1) * (ll + 1), :]
        if llmax > self.so3_lmax:
            cg_feat = self.cg_proj(latent[:, :so3_dim].to(self.prec)).reshape(
                n_at, so3_dim, self.cg_width
            )
            src1 = cg_feat[:, 1:4, :]
            src2 = cg_feat[:, 4:9, :]
            if llmax >= 3 and 3 not in blocks:
                blocks[3] = self._cg_couple(self.cg_123, src1, src2, self.cg_mix["l3"])
            if llmax >= 4 and 4 not in blocks:
                blocks[4] = self._cg_couple(self.cg_224, src2, src2, self.cg_mix["l4"])
            if llmax >= 5 and 5 not in blocks:
                blocks[5] = self._cg_couple(
                    self.cg_325, blocks[3], src2, self.cg_mix["l5"]
                )
            if llmax >= 6 and 6 not in blocks:
                blocks[6] = self._cg_couple(
                    self.cg_426, blocks[4], src2, self.cg_mix["l6"]
                )
        # l = 0: scalar coefficients dotted with the l = 0 radial block
        contrib = (
            coef_pair * radial.view(nf, ngrid, nsel, 1 + llmax, channels)[..., 0, :]
        ).sum(dim=-1)
        # l >= 1: flat-pair chunked contraction with the direction spherical
        # harmonics, both in the SeZM packed basis so the contraction is
        # exactly rotation invariant. Zero-length vectors only occur on
        # masked padding pairs.
        npair = nf * ngrid * nsel
        frame_ids = torch.arange(nf, device=radial.device).repeat_interleave(
            ngrid * nsel
        )
        idx_flat = frame_ids * nloc + coef_gather_index.reshape(npair)
        radial_flat = radial.view(npair, 1 + llmax, channels)
        vec = pair_vec.reshape(npair, 3).to(self.prec)
        r_hat = vec / vec.norm(dim=-1, keepdim=True).clamp_min(1e-12)
        parts: list[torch.Tensor] = []
        chunk = 1 << 19
        for start in range(0, npair, chunk):
            sl = slice(start, min(start + chunk, npair))
            y = real_spherical_harmonics(llmax, r_hat[sl], self.sh_norm, SQRT_2)
            acc = torch.zeros(sl.stop - sl.start, dtype=self.prec, device=radial.device)
            for ll in range(1, llmax + 1):
                y_l = y[:, ll * ll : (ll + 1) * (ll + 1)]
                u_l = y_l @ getattr(self, f"sh_transform_l{ll}").transpose(0, 1)
                c_l = blocks[ll].index_select(0, idx_flat[sl])
                angular = (c_l * u_l.unsqueeze(-1)).sum(dim=-2)
                acc = acc + (radial_flat[sl, ll, :] * angular).sum(dim=-1)
            parts.append(acc)
        contrib = contrib + torch.cat(parts).view(nf, ngrid, nsel)
        contrib = contrib * pair_keep.to(self.prec)
        return contrib.sum(dim=-1).unsqueeze(-1)

    def get_dim_fparam(self) -> int:
        """Get the number (dimension) of frame parameters of this fitting."""
        return self.numb_fparam

    def has_default_fparam(self) -> bool:
        """Check if the fitting has default frame parameters."""
        return False

    def get_default_fparam(self) -> torch.Tensor | None:
        """Get the default frame parameters."""
        return None

    def get_dim_aparam(self) -> int:
        """Get the number (dimension) of atomic parameters of this fitting."""
        return self.numb_aparam

    def get_sel_type(self) -> list[int]:
        """Get the selected atom types of this fitting.

        Only atoms with selected atom types contribute to the density.
        """
        sel_type: list[int] = []
        for ii in range(self.ntypes):
            if ii not in self.exclude_types:
                sel_type.append(ii)
        return sel_type

    def get_type_map(self) -> list[str] | None:
        """Get the name of each type of atoms."""
        return self.type_map

    def set_case_embd(self, case_idx: int) -> None:
        """Case embeddings are not supported; nothing to set."""
        del case_idx

    def compute_input_stats(self, merged: Any, **kwargs: Any) -> None:
        """The head keeps no input statistics; nothing to compute."""
        del merged, kwargs

    def change_type_map(
        self, type_map: list[str], model_with_new_type_stat: Any | None = None
    ) -> None:
        """Change the type related params to new ones, according to `type_map` and the original one in the model.
        If there are new types in `type_map`, statistics will be updated accordingly to `model_with_new_type_stat` for these new types.
        """
        assert self.type_map is not None, (
            "'type_map' must be defined when performing type changing!"
        )
        remap_index, _has_new_type = get_index_between_two_maps(self.type_map, type_map)
        self.type_map = type_map
        self.ntypes = len(type_map)
        self.reinit_exclude(map_atom_exclude_types(self.exclude_types, remap_index))
        self.type_embedding.change_type_map(type_map=type_map)

