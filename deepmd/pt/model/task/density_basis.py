"""Scalar radial basis expansion head for grid charge-density models.

EdenGNN-style density head: every real atom carries a vector of density
coefficients predicted from its (rotation-invariant) scalar descriptor, and
the density on a grid point is the sum over neighboring atoms of the
coefficient-weighted, element-dependent radial response of the grid-atom
distance. The response is built from a radial basis (Bessel by default)
concatenated with a type embedding of the neighbor atom and passed through a
radial MLP; an explicit C^3 cutoff envelope keeps the response strictly zero
at and beyond the cutoff.
"""

